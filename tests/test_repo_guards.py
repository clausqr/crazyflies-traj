"""
Repo-wide guards, each with a seeded violation:

* no em-dash anywhere (house style);
* no assistant-referencing files or mentions (the brain lives in the meta repo);
* flight is never enabled by default: the launch `fly` default, the node's
  `fly` parameter default, and the first traj_player / `rr traj run` example in
  every doc must be a dry run.
"""

import ast
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {'.git', 'build', 'install', 'log', '__pycache__', '.pytest_cache', 'rehearsal_out'}
TEXT_EXT = {'.py', '.md', '.sh', '.bash', '.csv', '.txt', '.xml', '.env', '.ini', '.cfg',
            '.toml', '.yaml', '.yml', ''}
LAUNCH = os.path.join(ROOT, 'ros2_ws', 'src', 'crazyflies_traj', 'launch',
                      'traj_player.launch.py')
NODE = os.path.join(ROOT, 'ros2_ws', 'src', 'crazyflies_traj', 'crazyflies_traj',
                    'traj_player_node.py')
EM_DASH = chr(0x2014)          # built, so this file stays clean itself
ASSISTANT = re.compile(r'\b(claude|anthropic)\b', re.IGNORECASE)


def repo_files():
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        for f in files:
            if os.path.splitext(f)[1] in TEXT_EXT or f in ('rr', 'Dockerfile'):
                yield os.path.join(d, f)


# ---- checkers (pure, seeded below) ------------------------------------------

def em_dash_findings(name, text):
    return [f'{name}:{i}' for i, line in enumerate(text.splitlines(), 1) if EM_DASH in line]


def assistant_findings(name, text):
    base = os.path.basename(name)
    out = []
    if base == 'CLAUDE.md' or '/.claude/' in name.replace(os.sep, '/') + '/':
        out.append(f'{name}: assistant file')
    out += [f'{name}:{i}' for i, line in enumerate(text.splitlines(), 1)
            if ASSISTANT.search(line)]
    return out


def launch_fly_default(src):
    """Return the default of the ('fly', default, ...) row in the launch ARGS table."""
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.Tuple) and len(node.elts) >= 2 and \
                isinstance(node.elts[0], ast.Constant) and node.elts[0].value == 'fly':
            return node.elts[1].value
    return None


def node_fly_default(src):
    m = re.search(r"(?:declare_parameter|\bp)\('fly',\s*([^)]*)\)", src)
    return m.group(1).strip() if m else None


def first_example_flies(text):
    """True when the FIRST player invocation in a doc enables flight."""
    for line in text.splitlines():
        if re.search(r'traj_player|rr traj run|traj run ', line):
            return bool(re.search(r'--fly\b|fly:=true', line))
    return False


# ---- the guards -------------------------------------------------------------

def test_no_em_dash_anywhere():
    bad = []
    for p in repo_files():
        with open(p, encoding='utf-8', errors='replace') as f:
            bad += em_dash_findings(os.path.relpath(p, ROOT), f.read())
    assert bad == [], bad


def test_no_assistant_files_or_mentions():
    bad = []
    for p in repo_files():
        rel = os.path.relpath(p, ROOT)
        if rel == os.path.join('tests', 'test_repo_guards.py'):
            continue                      # holds the pattern itself
        with open(p, encoding='utf-8', errors='replace') as f:
            bad += assistant_findings(rel, f.read())
    assert not os.path.exists(os.path.join(ROOT, 'CLAUDE.md'))
    assert not os.path.exists(os.path.join(ROOT, '.claude'))
    assert bad == [], bad


def test_fly_is_off_by_default_everywhere():
    with open(LAUNCH) as f:
        assert launch_fly_default(f.read()) == 'false'
    with open(NODE) as f:
        assert node_fly_default(f.read()) == 'False'
    docs = [p for p in repo_files() if p.endswith('.md')]
    assert docs
    for p in docs:
        with open(p) as f:
            assert not first_example_flies(f.read()), f'{p}: the first example must be a dry run'


# ---- seeded violations: every checker witnessed RED -------------------------

def test_seeded_em_dash():
    assert em_dash_findings('x.md', f'ok\nbad {EM_DASH} here\n') == ['x.md:2']


def test_seeded_assistant():
    assert assistant_findings('CLAUDE.md', '')
    assert assistant_findings('a/.claude/settings.json', '')
    assert assistant_findings('README.md', 'Generated by Claude')
    assert assistant_findings('x.py', '# anthropic') and not assistant_findings('x.py', 'ok')


def test_seeded_fly_defaults():
    assert launch_fly_default("ARGS = [('fly', 'true', 'x')]") == 'true'
    assert node_fly_default("p = self.declare_parameter('fly', True)") == 'True'
    assert first_example_flies('intro\n./rr traj run square_1m.csv --fly\n./rr traj run x.csv\n')
    assert first_example_flies('ros2 launch crazyflies_traj traj_player.launch.py fly:=true\n')
    assert not first_example_flies('./rr traj run a.csv\nlater: ./rr traj run a.csv --fly\n')
